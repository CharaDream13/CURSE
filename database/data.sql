-- =====================================================
-- 10. Контрольные запросы
-- =====================================================

-- Общее количество номеров
SELECT COUNT(*) AS total_rooms
FROM rooms;

-- Количество номеров по категориям
SELECT rc.code, rc.name, COUNT(r.id) AS room_count
FROM room_categories rc
LEFT JOIN rooms r ON r.category_id = rc.id
GROUP BY rc.id, rc.code, rc.name
ORDER BY rc.id;

-- Количество номеров по этажам
SELECT f.floor_number, COUNT(r.id) AS room_count
FROM floors f
LEFT JOIN rooms r ON r.floor_id = f.id
GROUP BY f.id, f.floor_number
ORDER BY f.floor_number;

-- Количество бронирований по статусам
SELECT bs.code, bs.name, COUNT(b.id) AS booking_count
FROM booking_statuses bs
LEFT JOIN bookings b ON b.status_code = bs.code
GROUP BY bs.code, bs.name
ORDER BY bs.code;
